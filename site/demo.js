import { encodeHex } from './hex.js';
// Original MCS-51 demonstration. Actual machine code, also used by the CPU smoke check.
export function demoHex() {
  const rom = new Uint8Array(256); rom.set([0x02, 0, 0x30]); rom.set([0x02, 0, 0x80], 0x0b);
  rom.set([
    0x75, 0xa0, 0x00, 0x75, 0x30, 0, // P2=0; scan position=0
    0xc2, 0xc4,                       // select S4..S7 column: P4.4=0
    0x75, 0x89, 0, 0x75, 0x8a, 0x18, 0x75, 0x8c, 0xfc,
    0x75, 0x88, 0x10, 0x75, 0xa8, 0x82, // Timer0 mode0, interrupt
    0xe5, 0xb0, 0x54, 0x0f, 0x44, 0xf0,
    0xf5, 0x80, 0x75, 0xa0, 0x80, 0x75, 0xa0, 0, 0x80, 0xf0,
  ], 0x30);
  rom.set([
    0xc0, 0xe0, 0xc0, 0xd0, 0xc0, 0x82, 0xc0, 0x83,
    0x75, 0x80, 0xff, 0x75, 0xa0, 0xe0, 0x75, 0xa0, 0,
    0x90, 0, 0xe0, 0xe5, 0x30, 0x93, 0xf5, 0x80,
    0x75, 0xa0, 0xc0, 0x75, 0xa0, 0,
    0x90, 0, 0xe8, 0xe5, 0x30, 0x93, 0xf5, 0x80,
    0x75, 0xa0, 0xe0, 0x75, 0xa0, 0,
    0x05, 0x30, 0x53, 0x30, 7,
    0xd0, 0x83, 0xd0, 0x82, 0xd0, 0xd0, 0xd0, 0xe0, 0x32,
  ], 0x80);
  rom.set([1, 2, 4, 8, 16, 32, 64, 128], 0xe0);
  rom.set([0xa4, 0xc0, 0xa4, 0x82, 0xff, 0xff, 0x92, 0xf9], 0xe8);
  return encodeHex(rom);
}
